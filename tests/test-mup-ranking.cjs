const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const sandbox={};
vm.runInNewContext(readFileSync(path.resolve(__dirname,'../mup-recommendations.js'),'utf8'),sandbox);
const r=sandbox.DayfolkMUP;
assert.equal(r.VERSION,'1.0.0');
const items=Array.from({length:54},(_,i)=>({id:'idea-'+i,kind:r.CATEGORIES[i%9],cost:i%2?0:20,guidance:i%3?'self_guided':'guided'}));
function eq(a,b,msg){assert.equal(JSON.stringify(a),JSON.stringify(b),msg);}
let cold=r.rank(items,[],'seed-1');
assert.equal(cold.length,54);
eq(cold,r.rank(items,[],'seed-1'),'Same seed and votes must reproduce the exact result');
assert.notEqual(JSON.stringify(cold),JSON.stringify(r.rank(items,[],'seed-2')),'Different seeds must vary order');
assert.equal(new Set(cold).size,54,'No duplicates in results');
let first=cold.slice(0,9).map(id=>items.find(x=>x.id===id).kind);
assert.equal(new Set(first).size,9,'First nine should represent all categories');
const one=r.model([{kind:'like',reason:'Feels local',category:'beach'}]);
const repeated=r.model(Array.from({length:1000},()=>({kind:'like',reason:'Feels local',category:'beach'})));
assert.equal(one.category.beach,1);
assert.equal(repeated.category.beach,3,'Preference growth must be capped');
assert.ok(repeated.attributes.local<=2);
const minus=r.model(Array.from({length:1000},()=>({kind:'dislike',reason:'Too expensive',category:'water'})));
assert.equal(minus.category.water,-3);
assert.ok(minus.attributes.budget>=-2);
const p=r.model([{kind:'dislike',reason:'Too touristy',category:'walk'}]);
assert.equal(p.counts.dislike,1);
assert.ok(Number.isFinite(r.score(items[0],p,'seed')));
const feedback=new Map([['idea-1',{kind:'like',reason:'The route length works for me'}]]);
const extracted=r.activityVotes(feedback,items);
assert.equal(extracted.length,1);
assert.equal(extracted[0].category,'nature');
assert.equal(r.rank([{...items[0]},{...items[0]}],[],'x').length,1);
assert.equal(r.rank([],[],'x').length,0);
console.log('Dayfolk MUP ranking regression tests: passed');
